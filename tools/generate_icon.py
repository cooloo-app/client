"""Generate transparent orange C/T PNGs, Windows ICOs and embedded RGBA data.

No third-party packages/fonts required. Geometry follows the website's C mark;
4x supersampling keeps the small title-bar icons legible. Run from any cwd.
"""
from pathlib import Path
import argparse
import math
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
SIZES = (16, 24, 32, 48, 64, 128, 256)
ORANGE = (0xD9, 0x62, 0x2B)


def pixels(size, mark='C'):
    result = bytearray()
    samples = 4
    for y in range(size):
        for x in range(size):
            hits = 0
            for sy in range(samples):
                for sx in range(samples):
                    dx = (x + (sx + .5) / samples) * 512 / size - 256
                    dy = (y + (sy + .5) / samples) * 512 / size - 256
                    if mark == 'T':
                        # Same 300-unit height and 60-unit stroke as the C.
                        inside = (-150 <= dx <= 150 and -150 <= dy <= -90) or (abs(dx) <= 30 and -90 <= dy <= 150)
                    else:
                        radius = math.hypot(dx, dy)
                        inside = 90 <= radius <= 150 and abs(math.atan2(dy, dx)) >= math.radians(40)
                    if inside:
                        hits += 1
            result.extend((*ORANGE, round(hits * 255 / samples**2)))
    return bytes(result)


def png(size, rgba):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    rows = b''.join(b'\0' + rgba[y*size*4:(y+1)*size*4] for y in range(size))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b''))


def dib(size, rgba):
    # ICO DIB: bottom-up BGRA bitmap plus 1-bit transparency mask.
    bitmap = bytearray()
    mask = bytearray()
    stride = ((size + 31) // 32) * 4
    for y in reversed(range(size)):
        rowmask = bytearray(stride)
        for x in range(size):
            r, g, b, a = rgba[(y*size+x)*4:(y*size+x+1)*4]
            bitmap.extend((b, g, r, a))
            if a == 0:
                rowmask[x//8] |= 0x80 >> (x % 8)
        mask.extend(rowmask)
    return struct.pack('<IiiHHIIiiII', 40, size, size*2, 1, 32, 0, len(bitmap), 0, 0, 0, 0) + bitmap + mask


def generate(output, mark):
    name = 'cooloo-text' if mark == 'T' else 'cooloo'
    header = 'embedded_text_icon.h' if mark == 'T' else 'embedded_icon.h'
    output.mkdir(parents=True, exist_ok=True)
    assets = ROOT / 'assets'
    assets.mkdir(exist_ok=True)
    images = {size: pixels(size, mark) for size in SIZES}
    (assets/f'{name}.png').write_bytes(png(256, images[256]))
    entries, payloads = [], []
    offset = 6 + 16*len(SIZES)
    for size in SIZES:
        data = png(size, images[size]) if size == 256 else dib(size, images[size])
        entries.append(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(data), offset))
        payloads.append(data)
        offset += len(data)
    (assets/f'{name}.ico').write_bytes(struct.pack('<HHH', 0, 1, len(SIZES)) + b''.join(entries + payloads))
    data = images[64]
    lines = [', '.join(str(v) for v in data[i:i+24]) for i in range(0, len(data), 24)]
    (output/header).write_text(
        f'/* Generated by tools/generate_icon.py; transparent orange {mark}, RGBA. */\n'
        '#ifndef COOLOO_EMBEDDED_ICON_H\n#define COOLOO_EMBEDDED_ICON_H\n'
        'static const unsigned char cooloo_icon_rgba[] = {\n    '
        + ',\n    '.join(lines) + '\n};\n#define COOLOO_ICON_SIZE 64\n#endif\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'build/generated')
    parser.add_argument('--mark', choices=('C', 'T', 'both'), default='both')
    args = parser.parse_args()
    for mark in ('C', 'T') if args.mark == 'both' else (args.mark,):
        generate(args.output_dir, mark)


if __name__ == '__main__':
    main()
