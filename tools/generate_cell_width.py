#!/usr/bin/env python3
"""Generate the pinned W/F table; no host locale or runtime Unicode dependency.

Input: https://www.unicode.org/Public/15.0.0/ucd/EastAsianWidth.txt
Usage: python3 tools/generate_cell_width.py EastAsianWidth.txt
"""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(source).hexdigest() == '743e7bc435c04ab1a8459710b1c3cad56eedced5b806b4659b6e69b85d0adf2a', 'unexpected Unicode input'
ranges = []
for line in source.decode('utf-8').splitlines():
    fields = line.split('#', 1)[0].strip().split(';')
    if len(fields) != 2 or fields[1].strip() not in ('W', 'F'):
        continue
    ends = fields[0].strip().split('..')
    first, last = int(ends[0], 16), int(ends[-1], 16)
    if ranges and first == ranges[-1][1] + 1:
        ranges[-1] = (ranges[-1][0], last)
    else:
        ranges.append((first, last))
output = Path(__file__).resolve().parents[1] / 'src/platform/cell_width.h'
output.write_text('''/* Generated by tools/generate_cell_width.py; Unicode 15.0.0.
 * Source: https://www.unicode.org/Public/15.0.0/ucd/EastAsianWidth.txt
 * Unicode data license: vendor/UNICODE-LICENSE.txt
 * Input SHA-256: %s
 * Codepoint policy, not grapheme shaping: W/F=2, A and others=1.
 */
#ifndef COOLOO_CELL_WIDTH_H
#define COOLOO_CELL_WIDTH_H
#include <stdint.h>
static int cell_columns(uint32_t cp) {
  static const struct { uint32_t first, last; } wide[] = {
%s
  };
  unsigned lo = 0, hi = sizeof(wide) / sizeof(wide[0]);
  while (lo < hi) {
    unsigned mid = lo + (hi - lo) / 2;
    if (cp < wide[mid].first) hi = mid;
    else if (cp > wide[mid].last) lo = mid + 1;
    else return 2;
  }
  return 1;
}
#endif
''' % (hashlib.sha256(source).hexdigest(), '\n'.join(
    '    {0x%X, 0x%X},' % pair for pair in ranges)), encoding='utf-8')
print(output)
