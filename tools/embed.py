#!/usr/bin/env python3
"""Embed the primary font. Usage: embed.py <font_ttf> <out_font.c>.

Workbench Lua modules are bundled by embed_workbench.py, which shares the
C string escaping helper below. Outputs are build artifacts (gitignored).
"""
import sys


def c_escape_string(data: bytes) -> str:
    out = []
    for line in data.split(b"\n"):
        s = line.decode("utf-8", "surrogateescape")
        s = s.replace("\\", "\\\\").replace('"', '\\"')
        out.append('"%s\\n"' % s)
    return "\n".join(out[:-1]) if out else '""'


def gen_font(font_path: str, out_path: str):
    with open(font_path, "rb") as f:
        data = f.read()
    parts = ["/* generated by tools/embed.py - do not edit */",
             "const unsigned char cooloo_embedded_font[] = {"]
    for i in range(0, len(data), 16):
        parts.append(",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    parts.append("};")
    parts.append("const unsigned int cooloo_embedded_font_len = %d;" % len(data))
    with open(out_path, "w") as f:
        f.write("\n".join(parts) + "\n")
    print("embed: %s <- %s (%d bytes)" % (out_path, font_path, len(data)))


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    gen_font(sys.argv[1], sys.argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main())
