#!/usr/bin/env python3
import pathlib, sys
out = pathlib.Path(sys.argv[1])
items = [('font', sys.argv[2]), ('icons', sys.argv[3]), ('monospace', sys.argv[4])]
with out.open('w') as f:
    f.write('/* generated by tools/embed_fonts.py - do not edit */\n')
    for name, path in items:
        data = pathlib.Path(path).read_bytes()
        f.write(f'const unsigned char cooloo_embedded_{name}[] = {{\n')
        for i in range(0, len(data), 16):
            f.write(','.join(f'0x{b:02x}' for b in data[i:i+16]) + ',\n')
        f.write('};\n')
        f.write(f'const unsigned int cooloo_embedded_{name}_len = {len(data)};\n')
