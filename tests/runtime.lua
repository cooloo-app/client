local r=host.runtime
local function poll_until(slot,match)
  local out='';local start=os.clock()
  while os.clock()-start<4 do
    local e=r.poll(slot);out=out..(e.stdout or '')..(e.stderr or '')
    if match(out,e) then return out,e end
  end
  error('runtime timeout: '..out)
end
assert(r.start(2));assert(r.send(2,'x=40; print("ready")'))
