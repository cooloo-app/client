local r,p=native_renderer,native_platform
local font=r.font.load('embedded:monospace',13.5)
assert(type(font)=='userdata')
local external=r.font.load('src/vendor/fonts/monospace.ttf',13.5)
assert(font:get_width('Hello')==external:get_width('Hello'))
assert(font:get_height()==external:get_height())
assert(not pcall(r.font.load,'missing-font.ttf',14))
assert(not pcall(r.font.load,'Makefile',14))
assert(not pcall(r.font.load,'embedded:font',0))
local icons=r.font.load('embedded:icons',14)
local normal=r.font.load('embedded:font',14)
assert(icons:get_width('abcd')~=normal:get_width('abcd'))
font:set_tab_width(3);assert(font:get_width('\t')==3)
assert(font:get_width('a\tb')==font:get_width('ab')+3)
font:set_tab_width(0);assert(font:get_width('\t')==0)
local text='Hello 中文🙂'
local sum=0
for _,cp in utf8.codes(text) do sum=sum+font:get_width(utf8.char(cp)) end
assert(sum==font:get_width(text),'whole and per-glyph width')
assert(font:get_width('a\nb')>=font:get_width('ab'),'newline traversal')
assert(font:get_width('\255\240\159')>=0,'strict malformed UTF-8')
local function background()
  r.begin_frame();r.set_clip_rect(0,0,960,640);r.draw_rect(0,0,960,640,{0,0,0})
end
background()
r.draw_rect(0,0,10,10,{255,0,0,128})
r.draw_rect(10,0,10,10,{255,0,0,0})
r.draw_rect(20,0,10,10)
r.draw_rect(30,0,10,10,{127.9,63.9,31.9})
r.set_clip_rect(-20,-20,22,22);r.draw_rect(0,20,100,100,{255,255,255})
r.set_clip_rect(0,0,960,640)
local x=r.draw_text(font,'a\tb',-1.8,50)
assert(x==-1+font:get_width('a\tb'))
r.draw_text(font,'abc',0,70,{255,255,255,0})
r.end_frame()
assert(pixel(0,0)==127,'alpha must actually blend')
assert(pixel(10,0)==0,'transparent rect')
assert(pixel(20,0)==255,'default white')
local a,b,c=pixel(30,0);assert(a==127 and b==63 and c==31,'channel conversion')
assert(pixel(0,20)==0,'clip intersection')
assert(pixel(2,72)==0,'transparent text')
assert(not pcall(r.draw_rect,0,0,1,1,{}))
assert(not pcall(r.draw_text,{},'x',0,0))
background();local doomed=r.font.load('embedded:font',15);r.draw_text(doomed,'GC while queued',0,100)
doomed=nil;collectgarbage('collect');r.end_frame()
r.show_debug(true);background();r.end_frame();r.show_debug(false)
local nilpath,why=p.absolute_path('does-not-exist');assert(nilpath==nil and type(why)=='string')
assert(p.resolve_path('./does-not-exist/../new-file')==p.resolve_path('new-file'))
local no,err=p.list_dir('does-not-exist');assert(no==nil and type(err)=='string')
no,err=p.info('does-not-exist');assert(no==nil and type(err)=='string')
p.cursor();p.cursor('arrow');p.cursor('hand');assert(not pcall(p.cursor,'bad'))
assert(p.fuzzy_match('abc','ac')==-10)
assert(p.fuzzy_match('abc','abc')==30)
assert(p.fuzzy_match('Abc','abc')==29)
assert(p.fuzzy_match('abc','')==-3)
assert(p.fuzzy_match('a b c','a c')==-10)
assert(p.fuzzy_match('abc','z')==nil)
